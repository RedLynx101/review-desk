"""Check every pinned Python dependency against a permissive-license allowlist.

    python scripts/check_licenses.py           # exit 1 if anything is not allowed
    python scripts/check_licenses.py --write   # also rewrite THIRD_PARTY_LICENSES.md

This repo is meant to be reusable by a client, so a copyleft dependency is a bug. PyMuPDF is
the usual trap in PDF work: it's AGPL or commercial, which is why this repo uses pypdfium2 and
pdfplumber instead.

Package metadata is often vague or missing, so `VERIFIED` records what was read by hand in each
package's license file. A pinned package with no entry fails the check until someone reads it.
"""

from __future__ import annotations

import argparse
import importlib.metadata as metadata
import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PIN_FILES = {"runtime": REPO / "requirements.txt", "development": REPO / "requirements-dev.txt"}
OUTPUT = REPO / "THIRD_PARTY_LICENSES.md"

#: Never allowed, even if a package were added to VERIFIED by mistake.
BANNED_PACKAGES = {"pymupdf", "fitz", "pymupdfb", "ghostscript", "pikepdf-gpl"}
COPYLEFT = re.compile(r"\b(AGPL|GPL|LGPL|SSPL|MPL|EUPL|CC-BY-SA|CC-BY-NC)\b", re.IGNORECASE)

#: Normalized package name to the license as read in the package's own files.
VERIFIED = {
    "annotated-types": "MIT",
    "anyio": "MIT",
    "cffi": "MIT-0",
    "charset-normalizer": "MIT",
    "click": "BSD-3-Clause",
    "colorama": "BSD-3-Clause",
    "cryptography": "Apache-2.0 OR BSD-3-Clause",
    "greenlet": "MIT AND PSF-2.0",
    "h11": "MIT",
    "idna": "BSD-3-Clause",
    "iniconfig": "MIT",
    "numpy": "BSD-3-Clause, with bundled 0BSD, MIT, Zlib and CC0-1.0 parts",
    "packaging": "Apache-2.0 OR BSD-2-Clause",
    "pdfminer-six": "MIT",
    "pdfplumber": "MIT",
    "pillow": "MIT-CMU",
    "playwright": "Apache-2.0",
    "pluggy": "MIT",
    "pycparser": "BSD-3-Clause",
    "pydantic": "MIT",
    "pydantic-core": "MIT",
    "pyee": "MIT",
    "pygments": "BSD-2-Clause",
    "pypdfium2": "BSD-3-Clause OR Apache-2.0; bundled PDFium build is BSD-3-Clause/Apache-2.0 with permissive parts",
    "pytest": "MIT",
    "reportlab": "BSD-3-Clause",
    "starlette": "BSD-3-Clause",
    "typing-extensions": "PSF-2.0",
    "typing-inspection": "MIT",
    "uvicorn": "BSD-3-Clause",
}

EXTERNAL = (
    ("Tesseract OCR", "Apache-2.0", "Installed separately and called as a program. Not bundled."),
    ("Bitstream Vera fonts", "Bitstream Vera license", "Ship inside ReportLab. Subsets get embedded in generated test PDFs, which the license allows."),
    ("LM Studio", "Proprietary, free to use", "Optional local model server, installed separately and reached over HTTP. Not bundled. Any OpenAI-compatible endpoint works."),
)


@dataclass
class Dependency:
    name: str
    version: str
    license: str
    group: str
    problem: str | None = None


def _normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def read_pins(path: Path) -> list[tuple[str, str]]:
    pins = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        name, _, version = line.partition("==")
        if not version:
            raise ValueError(f"{path.name}: {line!r} is not pinned to an exact version")
        pins.append((name.strip(), version.split(";")[0].strip()))
    return pins


def inspect() -> list[Dependency]:
    results = []
    for group, path in PIN_FILES.items():
        for name, version in read_pins(path):
            key = _normalize(name)
            license_text = VERIFIED.get(key, "")
            problem = None
            if key in BANNED_PACKAGES:
                problem = "banned package"
            elif not license_text:
                problem = "no hand-verified license entry"
            elif COPYLEFT.search(license_text):
                problem = f"copyleft license: {license_text}"
            else:
                try:
                    declared = metadata.metadata(name)
                except metadata.PackageNotFoundError:
                    declared = None
                if declared is not None:
                    text = " ".join(filter(None, [declared.get("License-Expression"), (declared.get("License") or "")[:200]]))
                    if COPYLEFT.search(text):
                        problem = f"metadata declares copyleft: {text}"
            results.append(Dependency(name, version, license_text, group, problem))
    return results


def render(dependencies: list[Dependency]) -> str:
    lines = [
        "# Third-party licenses",
        "",
        "Generated by `scripts/check_licenses.py` from the pinned requirements. Licenses were read from",
        "each package's own files; the script fails if a pin has no entry or a copyleft license shows up.",
        "",
    ]
    for group in PIN_FILES:
        lines += [f"## {group.capitalize()} dependencies", "", "| Package | Version | License |", "|---|---|---|"]
        lines += [f"| {d.name} | {d.version} | {d.license} |" for d in dependencies if d.group == group]
        lines.append("")
    lines += ["## External programs and assets", "", "| Name | License | Notes |", "|---|---|---|"]
    lines += [f"| {name} | {license_text} | {notes} |" for name, license_text, notes in EXTERNAL]
    lines += [
        "",
        "## Choices made because of licensing",
        "",
        "- PDF rendering and text with coordinates use pypdfium2 and pdfplumber. PyMuPDF would also work,",
        "  but it's AGPL or commercial, and a client reusing this code shouldn't inherit that.",
        "- The model client uses the standard library's `http.client`. HTTP libraries such as httpx pull in",
        "  certifi, which is MPL-2.0, and they read proxy settings and can follow redirects, which this app",
        "  shouldn't do with a document.",
        "- The server uses Starlette rather than FastAPI. FastAPI adds nothing this app needs, and its docs pages",
        "  load from a CDN by default, which would break the no-outside-connections rule.",
        "- The PDFium build bundles permissive third-party parts (FreeType under its FTL option, ICU, libjpeg-turbo,",
        "  OpenJPEG, libpng, zlib and others). Their notices are in the pypdfium2 wheel's `BUILD_LICENSES` folder.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help=f"rewrite {OUTPUT.name}")
    args = parser.parse_args(argv)

    dependencies = inspect()
    problems = [d for d in dependencies if d.problem]
    for dep in problems:
        print(f"FAIL {dep.name}=={dep.version}: {dep.problem}", file=sys.stderr)
    if args.write:
        OUTPUT.write_text(render(dependencies), encoding="utf-8", newline="\n")
    print(f"{len(dependencies)} pinned dependencies checked, {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
